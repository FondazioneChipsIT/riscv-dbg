set -euo pipefail

readonly CI_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# Repository root (Bender package root): <root>/RVDBG4614-main/testbench/riscv-dbg/ci
readonly ROOT="$(cd "${CI_DIR}/../../../.." && pwd)"
readonly LICENSE_PATTERN='SPDX-License-Identifier|[Ll]icensed under|[Ll]icense details|Solderpad Hardware License|Permission to use, copy|Copying and distribution|Redistribution and use|This copyrighted material'

cd "${ROOT}"

status=0
while IFS= read -r -d '' file; do
  [[ -f "${file}" ]] || continue
  if ! head -n 40 "${file}" | grep -Eq "${LICENSE_PATTERN}"; then
    echo "::error file=${file}::No license notice found in the first 40 lines"
    status=1
  fi
done < <(
  git ls-files -z \
    '*.c' '*.cc' '*.cpp' '*.h' '*.ld' '*.mk' '*.py' '*.sh' \
    '*.sv' '*.svh' '*.tcl' '*.v' '*.yaml' '*.yml' '*.S' \
    'Makefile' \
    ':(exclude)RVDBG4614-main/rtl/common_cells/**' \
    ':(exclude)RVDBG4614-main/testbench/rtl/**' \
    ':(exclude)RVDBG4614-main/synthesis/**' \
    ':(exclude)RVDBG4614-main/PlaceAndRoute/**' \
    ':(exclude)release/**'
)
# Vendored third-party code (common_cells, Croc SoC testbench IP, CVE2) is
# covered by the license files shipped with it; netlists and other views in
# synthesis/, PlaceAndRoute/ and release/ are generated by the flow.

exit "${status}"
